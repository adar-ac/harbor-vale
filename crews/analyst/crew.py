"""Crew 1 (analyst): a real CrewAI crew over data/raw/telco.csv.

Three agents (Profiler, Cleaner, Contract Author). Cleaning and contract generation
run inside deterministic tools (crews/analyst/tools.py); the agents call those tools
and write only the narrative outputs (insights.md, eda_report.html). The tools are
bound to fixed paths and take no arguments, so an agent can't point them elsewhere.

stub.py is kept as an offline fallback (see flows/main_flow.py).
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()  # GEMINI_API_KEY, CREWAI_TRACING_ENABLED, ... before crewai reads them

from crewai import LLM, Agent, Crew, Process, Task  # noqa: E402
from crewai.tools import tool  # noqa: E402

from crews.analyst import tools as T  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
RAW_PATH = ROOT / "data" / "raw" / "telco.csv"
INSIGHTS_FILENAME = "insights.md"
EDA_FILENAME = "eda_report.html"
# "gemini/..." routes to CrewAI's native Gemini provider (google-genai SDK), which reads
# GEMINI_API_KEY. gemini-3.8-flash: current stable Flash, free tier (checked 2026-10-12).
MODEL = os.getenv("MODEL", "gemini/gemini-3.8-flash")


def _json(obj) -> str:
    return json.dumps(obj, indent=2, default=str)


def _strip_fences(text: str) -> str:
    """LLMs often wrap whole documents in ```html / ```markdown fences."""
    m = re.fullmatch(r"\s*```[a-zA-Z]*\n(.*?)\n?```\s*", text, flags=re.DOTALL)
    return (m.group(1) if m else text).strip() + "\n"


def build_crew(out_dir: Path, raw_path: Path = RAW_PATH) -> tuple[Crew, dict[str, Task]]:
    clean_path = out_dir / T.CLEAN_FILENAME
    contract_path = out_dir / T.CONTRACT_FILENAME

    @tool("profile_raw_data")
    def profile_raw_data() -> str:
        """Profile the raw Telco CSV: row count, columns, pandas dtypes, nulls, blank
        strings, cardinality, numeric ranges. Takes no arguments."""
        return _json(T.profile(raw_path))

    @tool("clean_dataset")
    def clean_dataset() -> str:
        """Apply the approved cleaning steps to the raw CSV and write clean.csv.
        Returns a JSON summary of what changed. Takes no arguments."""
        return _json(T.clean(raw_path, clean_path))

    @tool("write_dataset_contract")
    def write_dataset_contract() -> str:
        """Measure the cleaned CSV and write dataset_contract.json. Returns the
        contract that was written. Takes no arguments. Run clean_dataset first."""
        return _json(T.write_contract(clean_path, contract_path))

    @tool("eda_summary")
    def eda_summary() -> str:
        """Churn rate overall, churn rate per category, and numeric summaries
        (overall / churned / retained) measured on clean.csv. Takes no arguments."""
        return _json(T.eda_summary(clean_path))

    llm = LLM(model=MODEL, temperature=0.2)
    grounding = (
        "Every number you state must be copied from a tool result. Never estimate, "
        "compute or invent statistics yourself."
    )

    profiler = Agent(
        role="Data Profiler",
        goal="Describe the raw Telco churn dataset's structure and data quality accurately.",
        backstory="A careful analyst who reports only what the profiling tool measured. " + grounding,
        tools=[profile_raw_data, eda_summary],
        llm=llm,
        verbose=True,
    )
    cleaner = Agent(
        role="Data Cleaner",
        goal="Produce clean.csv by running the approved cleaning tool and explain what it did.",
        backstory=(
            "A data engineer who executes approved cleaning decisions exactly. You do not "
            "invent new cleaning steps or change the approved ones. " + grounding
        ),
        tools=[clean_dataset],
        llm=llm,
        verbose=True,
    )
    author = Agent(
        role="Contract Author",
        goal="Publish dataset_contract.json for the cleaned data and summarise the key insights.",
        backstory=(
            "You own the handoff to the modelling crew. The contract is generated by a tool "
            "from the cleaned file; you never edit or restate its values from memory. " + grounding
        ),
        tools=[write_dataset_contract, eda_summary],
        llm=llm,
        verbose=True,
    )

    profile_task = Task(
        description=(
            "Call profile_raw_data. Report the row and column count, each column's dtype, "
            "missing values (nulls and blank strings), and any column that is numeric but "
            "stored as text."
        ),
        expected_output="A concise bullet-point data-quality profile of the raw CSV.",
        agent=profiler,
    )
    clean_task = Task(
        description=(
            "Call clean_dataset exactly once. The approved decisions, already made, are: "
            "convert TotalCharges with pd.to_numeric(errors='coerce'); drop the rows where "
            "TotalCharges is blank (tenure=0 customers who were never billed, so they have no "
            "billing history to model); keep all 21 columns. Do not propose other cleaning. "
            "Report rows in, rows dropped, rows out, and why the rows were dropped."
        ),
        expected_output="A short cleaning log quoting the tool's row counts.",
        agent=cleaner,
        context=[profile_task],
    )
    contract_task = Task(
        description=(
            "Call write_dataset_contract exactly once. Then summarise the contract: target "
            "column, expected row count, and each column's dtype/kind, monetary columns and "
            "units. Quote values from the tool result only."
        ),
        expected_output="A summary of the published dataset contract.",
        agent=author,
        context=[clean_task],
    )
    eda_task = Task(
        description=(
            "Call eda_summary. Write a self-contained HTML EDA report for the cleaned Telco "
            "dataset: a title, an overview (rows, churn rate), a section on the cleaning that "
            "was applied (from the context), HTML tables of churn rate by category for every "
            "categorical column, a table of numeric summaries (churned vs retained), and a "
            "short 'Key observations' list. Use inline CSS only, no JavaScript, no external "
            "resources. Every number must come from eda_summary or the context."
        ),
        expected_output="A complete HTML document starting with <!DOCTYPE html>. Output only the HTML.",
        agent=profiler,
        context=[profile_task, clean_task],
    )
    insights_task = Task(
        description=(
            "Call eda_summary. Write insights.md for the modelling crew: the strongest churn "
            "drivers (segments whose churn rate differs most from the overall rate), notable "
            "numeric differences between churned and retained customers, data-quality notes "
            "from cleaning, and caveats (class balance, correlated features such as tenure "
            "and TotalCharges). Every number must come from eda_summary or the context."
        ),
        expected_output="A Markdown document with headings and bullet points. Output only the Markdown.",
        agent=author,
        context=[profile_task, clean_task, contract_task],
    )

    tasks = {
        "profile": profile_task,
        "clean": clean_task,
        "contract": contract_task,
        "eda": eda_task,
        "insights": insights_task,
    }
    crew = Crew(
        agents=[profiler, cleaner, author],
        tasks=list(tasks.values()),
        process=Process.sequential,
        verbose=True,
    )
    return crew, tasks


def run(out_dir: Path) -> dict[str, Path]:
    """Run the analyst crew; write clean.csv, dataset_contract.json, insights.md and
    eda_report.html into out_dir. Same return shape as stub.run()."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "data": out_dir / T.CLEAN_FILENAME,
        "contract": out_dir / T.CONTRACT_FILENAME,
        "insights": out_dir / INSIGHTS_FILENAME,
        "eda_report": out_dir / EDA_FILENAME,
    }
    # Remove stale outputs so a run where an agent skipped its tool can't pass on old files.
    for p in paths.values():
        p.unlink(missing_ok=True)

    crew, tasks = build_crew(out_dir)
    crew.kickoff()

    for key in ("data", "contract"):
        if not paths[key].exists():
            raise RuntimeError(f"analyst crew finished without writing {paths[key].name}; "
                               "an agent did not call its tool")
    # Belt and braces: the contract on disk must be exactly what the code derives.
    on_disk = json.loads(paths["contract"].read_text(encoding="utf-8"))
    if T.build_contract(paths["data"]) != on_disk:
        raise RuntimeError("dataset_contract.json differs from the contract measured from clean.csv")

    paths["eda_report"].write_text(_strip_fences(tasks["eda"].output.raw), encoding="utf-8")
    paths["insights"].write_text(_strip_fences(tasks["insights"].output.raw), encoding="utf-8")
    return paths
